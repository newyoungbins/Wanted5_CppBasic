#include <iostream>

#define Square(x) ((x) * (x))

// inline 함수
inline int Square2(int x)
{
	return x * x;
}

int main()
{
	//프로그램의 빌드 과정
	//C++ 소스 코드가 실행 파일로 만들어지는 과정은 교육 목적상 네 단계로 나누어 설명할 수 있다.
	// 1. 전처리	(#include, #define, #if 와 같은 전처리 지시문을 처리한다.)
	// 2. 컴파일	(컴파일러는 전처리 결과로 만들어진 번역 단위를 분석한다.)
	// 3. 어셈블	(어셈블러는 컴파일러가 생성한 수준의 코드를 기계어로 변환하고 목적 파일을 만든다.)
	// 4. 링크		(링커는 여러 목적 파일과 필요한 라이브러리를 결합해 실행 파일을 만든다.)


	// 인라인(in-Line) 함수
	std::cout << Square(3) << "\n";
	// 전처리기는 Square(3)을 매크로에 정의된 내용으로 치환한다.
	// 전처리 과정을 거친 코드는 다음과 같은 형태가 된다.
	std::cout << ((3) * (3)) << "\n";
	// 매크로 함수의 특징
	// 매크로 함수는 함수 호출 구문을 사용하지만 실제 함수는 아니다.
	// 전처리 단계에서 호출 부분이 매크로에 정의된 코드로 치환되므로 함수 호출 과정이 발생하지 않는다.
	// 함수 호출 과정이 사라지면 호출과 반환에 필요한 작업이 줄어들어 성능상 이점을 얻을 수 있다.
	// 이처럼 함수 호출 대신 함수의 코드를 호출 위치에 배치하는 것을 함수 인라인화 라고 한다.

	// 매크로 함수는 일반 함수와 달리 자료형을 검사하지 않는다. 
	// 또한 전달한 표현식이 매크로 내부에서 여러 번 사용될 수 있으므로 주의해야한다.
	int number = 3;
	int result = Square(++number);
	// 위 코드는 ++number가 두 번 실행될 수 있으므로 예상하지 못한 결과가 발생한다.
	// 따라서 단순한 계산을 함수처럼 작성할 때는 매크로보다 일반 함수나 인라인 함수를 사용하는 것이 안전하다.

	// C++ 인라인 함수
	// C++에서는 inline 키워드를 사용해 인라인 함수를 선언할 수 있다.
	std::cout << Square(3) << "\n";
	// 인라인 함수는 일반 함수이므로 매크로와 달리 매개변수와 반환값의 자료형을 검사한다.
	// 컴파일러는 함수의 크기와 호출 상황 등을 고려해 실제로 인라인화 할지 결정한다.
	// 따라서 inline 키워드를 붙였다고 해서 함수가 반드시 인라인화 되는 것은 아니다.
	// 반대로 inline 키워드가 없는 함수도 컴파일러의 판단에 따라 인라인화 될 수 있다.

	std::cin.get();
}